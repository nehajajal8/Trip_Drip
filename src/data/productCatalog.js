/**
 * Filter catalog items by matching category keyword
 */
export function getProductsForCategory(categoryKey = "") {
  const norm = categoryKey.toLowerCase();
  return PRODUCT_CATALOG.filter((p) => {
    if (!categoryKey || categoryKey === "all") return true;
    if (p.category === categoryKey) return true;
    if (norm.includes("top") && (p.category === "short_sleeve_top" || p.category === "long_sleeve_top")) return true;
    if (norm.includes("bottom") && (p.category === "trousers" || p.category === "shorts")) return true;
    if (norm.includes("shoe") || norm.includes("footwear")) return p.category === "shoes";
    if (norm.includes("jacket") || norm.includes("coat") || norm.includes("outwear")) return p.category === "long_sleeve_outwear" || p.category === "short_sleeve_outwear";
    if (norm.includes("dress")) return p.category.includes("dress");
    return p.category.toLowerCase().includes(norm) || p.name.toLowerCase().includes(norm);
  });
}

