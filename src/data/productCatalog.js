export function getBrandComparison(categoryKey = "short_sleeve_top", maxBudget = Infinity) {
  const matching = getProductsForCategory(categoryKey);
  const brands = ["Zara", "H&M", "Uniqlo", "Westside"];
  const comparison = brands.map((brandName) => {
    const items = matching.filter((p) => p.brand.toLowerCase() === brandName.toLowerCase());
    const bestFit = items.find((i) => i.price <= maxBudget) || items[0] || null;
    return {
      brand: brandName,
      item: bestFit,
      inBudget: bestFit ? bestFit.price <= maxBudget : false,
      alternatives: items,
    };
  });
  return comparison;
}
